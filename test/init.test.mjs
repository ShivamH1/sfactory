import { test } from "node:test";
import assert from "node:assert/strict";
import { writeFileSync, mkdirSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { tmpRepo, sh } from "./helpers.mjs";
import { main } from "../src/cli.mjs";
import { validateConfig } from "../src/config.mjs";

const run = async (cwd, args) => { let out = "", err = ""; const code = await main(args, { cwd, stdout: (s) => (out += s), stderr: (s) => (err += s) }); return { code, out, err }; };
const cfgOf = (root) => JSON.parse(readFileSync(join(root, "sfactory.config.json"), "utf8"));

test("init: a node monorepo with spec tree, prisma and env files is guessed and validates", async () => {
  const root = tmpRepo();
  writeFileSync(join(root, "package.json"), JSON.stringify({ name: "acme", scripts: { test: "vitest", build: "tsc" }, workspaces: ["apps/*"] }));
  writeFileSync(join(root, "pnpm-lock.yaml"), "");
  writeFileSync(join(root, "CLAUDE.md"), "x\n"); writeFileSync(join(root, "AGENTS.md"), "x\n");
  for (const d of ["spec/modules", "spec/plans", "spec/decisions", "apps/api/prisma/migrations", "apps/api"]) mkdirSync(join(root, d), { recursive: true });
  writeFileSync(join(root, "apps/api/.env"), "SECRET=hunter2\n"); writeFileSync(join(root, "apps/api/.env.example"), "SECRET=\n"); writeFileSync(join(root, ".env.local"), "A=1\n");
  sh("git", ["branch", "development"], root); sh("git", ["branch", "feature/one"], root);
  const r = await run(root, ["init"]);
  assert.equal(r.code, 0, r.err);
  const c = cfgOf(root);
  assert.deepEqual(validateConfig(c), []);
  assert.equal(c.project, "acme"); assert.equal(c.commands.suite, "pnpm test"); assert.equal(c.commands.build, "pnpm run build");
  assert.equal(c.worktrees.integrationBranch, "development"); assert.equal(c.worktrees.baseRule, "newest-feature-branch");
  assert.equal(c.record.style, "spec-tree"); assert.deepEqual(c.rules, ["CLAUDE.md", "AGENTS.md"]);
  assert.deepEqual(c.hotspots, ["packages/*"]); assert.equal(c.migrations.dir, "apps/api/prisma/migrations");
  assert.deepEqual(c.secrets.neverHandToAgents, [".env.local", "apps/api/.env"]);
  assert.match(r.out, /generated by sfactory init/); assert.match(r.out, /defaults \(left alone\):.*limits/);
  assert.match(r.out, /apps\/api\/\.env/); assert.ok(!r.out.includes("hunter2"));
  assert.match(readFileSync(join(root, ".gitignore"), "utf8"), /^\.sfactory\/$/m);
});

test("init: a python uv repo gets uv run pytest; a bare repo gets a failing placeholder that still validates", async () => {
  const py = tmpRepo(); writeFileSync(join(py, "pyproject.toml"), "[project]\n");
  assert.equal((await run(py, ["init"])).code, 0);
  assert.equal(cfgOf(py).commands.suite, "uv run pytest");
  const bare = tmpRepo();
  const r = await run(bare, ["init"]);
  assert.equal(r.code, 0); assert.deepEqual(validateConfig(cfgOf(bare)), []);
  assert.match(r.out, /NOTHING FOUND/);
  assert.equal(cfgOf(bare).project.length > 0, true);
});

test("init: refuses an existing config without --force, replaces it with --force; .gitignore line added once", async () => {
  const root = tmpRepo();
  assert.equal((await run(root, ["init"])).code, 0);
  const again = await run(root, ["init"]);
  assert.equal(again.code, 2); assert.match(again.err, /CONFIG_EXISTS/);
  writeFileSync(join(root, "sfactory.config.json"), "{}");
  assert.equal((await run(root, ["init", "--force"])).code, 0);
  assert.deepEqual(validateConfig(cfgOf(root)), []);
  assert.equal(readFileSync(join(root, ".gitignore"), "utf8").match(/\.sfactory\//g).length, 1);
  assert.ok(!existsSync(join(root, ".sfactory")));
});
