import { existsSync } from "node:fs";
import { join } from "node:path";
import { register } from "../registry.mjs";
import { fail } from "../errors.mjs";
import { findRepoRoot, validateConfig } from "../config.mjs";
import { inspectRepo, writeInit, CONFIG_FILE } from "../init.mjs";

register("init", (args, io) => {
  const root = findRepoRoot(io.cwd);
  if (existsSync(join(root, CONFIG_FILE)) && args.flags.force !== true) fail("CONFIG_EXISTS", `${join(root, CONFIG_FILE)} exists; use --force to replace it`);
  const { config, guesses, defaults, secrets } = inspectRepo(root);
  const errs = validateConfig(config);
  if (errs.length) fail("INVALID_CONFIG", `init produced an invalid config:\n  ${errs.join("\n  ")}`);
  const { file, ignored } = writeInit(root, config);
  io.stdout(`generated by sfactory init: ${file}\n`);
  for (const g of guesses) io.stdout(`guessed  ${g}\n`);
  io.stdout(`defaults (left alone): ${defaults.join(", ") || "none"}\n`);
  if (secrets.length) io.stdout(`secrets: ${secrets.join(", ")} are listed in secrets.neverHandToAgents (their contents were never read)\n`);
  if (ignored) io.stdout("added .sfactory/ to .gitignore\n");
  io.stdout("review the file, then run: sfactory doctor\n");
  return 0;
});
